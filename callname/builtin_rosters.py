def list_builtin() -> list[BuiltinRoster]:
    """下拉框用的内置名单清单。"""
    return [
        BuiltinRoster(key=key, label=f"{key} 班（{len(names)} 人）", count=len(names))
        for key, names in BUILTIN_ROSTERS.items()
    ]


def get_builtin(key: str) -> BuiltinRosterData:
    """按 key 取内置名单内容。"""
    names = BUILTIN_ROSTERS.get(key)
    if names is None:
        raise RosterError("BAD_KEY", f"没有名为 {key} 的内置名单")
    return BuiltinRosterData(key=key, names=list(names))


